"""Shared safety rules for server-projected semantic-read links.

This module is deliberately field-only and has no API/router imports.  LLM
transport and assistant persistence can therefore apply the same canonical URL
allowlist without creating an import cycle or passing raw source bodies.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from urllib.parse import parse_qsl, unquote, urlsplit
from uuid import UUID
from typing import Any


_CITATION_HASH_RE = re.compile(r"^[0-9a-fA-F]{64}$")
_MAX_URL_LENGTH = 2_048
_FORBIDDEN_QUERY_KEYS = frozenset(
    {
        "token",
        "access_token",
        "auth_token",
        "refresh_token",
        "session_token",
        "api_key",
        "key",
        "secret",
        "password",
        "authorization",
        "cookie",
    }
)


def _uuid_text(value: Any) -> str | None:
    try:
        return str(UUID(str(value)))
    except (AttributeError, TypeError, ValueError):
        return None


def safe_verified_media_read_url(
    value: Any,
    *,
    target_kind: str,
    locator: Mapping[str, Any] | None,
    unit_id: str | None,
    source_id: str | None,
) -> str | None:
    """Return a canonical same-origin URL or ``None``.

    Only URL shapes generated by the current docs, conversation, knowledge,
    and verified media readers are accepted.  The caller remains responsible
    for success/complete/body-hash/current-reader checks.
    """

    if not isinstance(value, str) or not value.startswith("/") or value.startswith("//"):
        return None
    if len(value) > _MAX_URL_LENGTH:
        return None
    decoded = unquote(value)
    if (
        decoded.startswith("//")
        or "\\" in decoded
        or any(ord(char) < 32 or ord(char) == 127 for char in decoded)
    ):
        return None
    parts = urlsplit(value)
    if parts.scheme or parts.netloc or parts.fragment:
        return None
    query = parse_qsl(parts.query, keep_blank_values=True)
    query_keys = [key.casefold() for key, _ in query]
    if len(set(query_keys)) != len(query_keys):
        return None
    if set(query_keys) & _FORBIDDEN_QUERY_KEYS:
        return None

    kind = str(target_kind or "").strip().casefold()
    expected_id = _uuid_text((locator or {}).get("id"))
    expected_session = _uuid_text((locator or {}).get("session_id"))
    if kind == "docs":
        if not expected_id or (locator or {}).get("kind") != "docs_node":
            return None
        return value if parts.path == "/docs" and query == [("node_id", expected_id)] else None
    if kind == "conversation":
        if (
            not expected_id
            or not expected_session
            or (locator or {}).get("kind") != "conversation_message"
            or parts.path != "/chat"
        ):
            return None
        if query == [("s", expected_session), ("message", expected_id)]:
            return value
        if query == [("session", expected_session), ("message", expected_id)]:
            return f"/chat?s={expected_session}&message={expected_id}"
        return None
    if kind == "knowledge":
        if not expected_id or (locator or {}).get("kind") != "knowledge_document":
            return None
        return (
            value
            if parts.path == f"/api/knowledge/documents/{expected_id}" and not query
            else None
        )
    if kind != "media":
        return None

    expected_unit = _uuid_text(unit_id)
    expected_source = _uuid_text(source_id)
    if expected_unit and parts.path == f"/api/search/media/{expected_unit}/content":
        for key, query_value in query:
            if key not in {"project_id", "space_id"} or not _uuid_text(query_value):
                return None
        return value

    known_single_id_paths = {
        "/api/generated-media/",
        "/api/docs/attachments/",
        "/api/v1/meeting-processing/jobs/",
    }
    for prefix in known_single_id_paths:
        if (
            parts.path.startswith(prefix)
            and _uuid_text(parts.path[len(prefix) :]) == expected_source
            and not query
        ):
            return value

    task_prefix = "/api/tasks/"
    if parts.path.startswith(task_prefix) and not query:
        segments = parts.path[len(task_prefix) :].split("/attachments/")
        if (
            len(segments) == 2
            and all(_uuid_text(item) for item in segments)
            and (expected_source is None or _uuid_text(segments[1]) == expected_source)
        ):
            return value

    operations_prefix = "/api/operations/media/assets/"
    if parts.path.startswith(operations_prefix) and parts.path.endswith("/preview"):
        asset_id = parts.path[len(operations_prefix) : -len("/preview")]
        if (
            _uuid_text(asset_id)
            and (expected_source is None or _uuid_text(asset_id) == expected_source)
            and len(query) == 1
            and query[0][0] == "expected_sha256"
            and _CITATION_HASH_RE.fullmatch(query[0][1] or "")
        ):
            return value
    return None
